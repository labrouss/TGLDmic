#!/usr/bin/env python3
"""Turn a SOF dmesg capture (sof_debug=0xa00 + dyndbg) into a C replay table.

usage: extract-ipc.py dmesg-capture-pcm6-S32_LE.txt > kext/TGLDmic/IpcReplay.hpp

Each IPC3 message = 8-byte sof_ipc_cmd_hdr {size, cmd} + payload. The kernel log
prints the payload *after* the header, so we rebuild the header here.
"""
import re, sys

CMD_NAMES = {
    0x30010000: "TPLG_COMP_NEW", 0x30020000: "TPLG_COMP_FREE", 0x30030000: "TPLG_COMP_CONNECT",
    0x30100000: "TPLG_PIPE_NEW", 0x30110000: "TPLG_PIPE_FREE", 0x30130000: "TPLG_PIPE_COMPLETE",
    0x30200000: "TPLG_BUFFER_NEW", 0x30210000: "TPLG_BUFFER_FREE",
    0x50010000: "COMP_SET_VALUE", 0x50030000: "COMP_SET_DATA",
    0x60010000: "STREAM_PCM_PARAMS", 0x60030000: "STREAM_PCM_FREE",
    0x60040000: "STREAM_TRIG_START", 0x60050000: "STREAM_TRIG_STOP",
    0x80010000: "DAI_CONFIG",
}

def parse(path):
    """'widget X setup complete' is logged AFTER that widget's IPCs; routes/triggers BEFORE."""
    msgs, cur, pending, ctx = [], None, [], ""
    for line in open(path, errors="replace"):
        m = re.search(r"widget (\S+) (setup complete|freed)", line)
        if m:
            for x in pending: x["ctx"] = f"widget {m.group(1)}"
            pending = []
            continue
        m = re.search(r"(setting up route .*|Entry: (?:trigger \(cmd: \d\)|hw_free|hw_params)|tplg: complete pipeline .*)", line)
        if m:
            ctx = m.group(1).strip(); pending = []
            continue
        m = re.search(r"ipc tx: (0x[0-9a-f]+)$", line.strip())
        if m:
            cur = {"cmd": int(m.group(1), 16), "words": [], "ctx": ctx}
            msgs.append(cur); pending.append(cur)
            continue
        m = re.search(r"Message payload: ([0-9a-f]{8}): ((?:[0-9a-f]{8} ?)+)", line)
        if m and cur is not None:
            cur["words"] += [int(w, 16) for w in m.group(2).split()]
    return msgs

def main():
    msgs = parse(sys.argv[1])
    start = next(i for i, m in enumerate(msgs) if m["cmd"] == 0x60040000)
    stop = next(i for i, m in enumerate(msgs) if m["cmd"] == 0x60050000)
    phases = {"setup": msgs[:start], "start": msgs[start:start + 1],
              "stop": msgs[stop:stop + 2], "teardown": msgs[stop + 2:]}
    print("// Generated by linux/extract-ipc.py from a Linux SOF v2.2 capture on HP EliteBook 840 G8")
    print("// Pipeline 10: DMIC0.IN -> EQIIR10.0 (highpass) -> Dmic0 (volume) -> PCM6C host, 48 kHz, 4 ch, S32_LE")
    print("#pragma once\n#include <stdint.h>\n")
    print("struct IpcMsg { uint32_t cmd; uint16_t words; uint16_t patch; const uint32_t *data; const char *name; };")
    print("enum : uint16_t { kPatchNone = 0, kPatchPcmParams = 1 };\n")
    for ph, lst in phases.items():
        for i, m in enumerate(lst):
            size = 8 + 4 * len(m["words"])
            w = [size, m["cmd"]] + m["words"]
            body = ", ".join("0x%08x" % x for x in w)
            print(f"// {ph}[{i}] {CMD_NAMES.get(m['cmd'], hex(m['cmd']))}  ({m['ctx']})")
            print(f"static const uint32_t ipc_{ph}_{i}[] = {{ {body} }};")
    print()
    for ph, lst in phases.items():
        print(f"static const IpcMsg kIpc_{ph}[] = {{")
        for i, m in enumerate(lst):
            patch = "kPatchPcmParams" if m["cmd"] == 0x60010000 else "kPatchNone"
            name = CMD_NAMES.get(m["cmd"], "UNKNOWN")
            print(f"  {{ 0x{m['cmd']:08x}, {len(m['words']) + 2}, {patch}, ipc_{ph}_{i}, \"{name}\" }},")
        print("};")
    print("""
// STREAM_PCM_PARAMS layout (word index into the full message incl. 8-byte header):
//  [2] comp_id (host PCM6C = 0x32)   [8] buffer.phy_addr (page table, <4 GB)
//  [9] buffer.pages                  [10] buffer.size (ring bytes)
//  [14] direction (1 = capture)       [15] frame_fmt (2 = S32_LE)  [17] rate
//  [18] stream_tag (lo16) | channels (hi16)   [20] host_period_bytes
enum { kPcmParamPhy = 8, kPcmParamPages = 9, kPcmParamSize = 10, kPcmParamTagCh = 18, kPcmParamPeriod = 20 };""")

if __name__ == "__main__":
    main()
